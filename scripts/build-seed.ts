/**
 * Generates supabase/seed.sql from tenants/<slug>/tenant.json + tenants/<slug>/kb/*.md
 * and writes tenants/tenant.schema.json for editor autocompletion.
 * Usage: npm run seed:build   (CI fails if the committed seed.sql is out of date)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { TenantConfigSchema } from "../src/lib/tenants/config.ts";
import { buildTenantSeedSql, type KbDoc } from "../src/lib/tenants/seed-sql.ts";

const root = join(import.meta.dirname, "..");
const tenantsDir = join(root, "tenants");

const slugs = readdirSync(tenantsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(tenantsDir, d.name, "tenant.json")))
  .map((d) => d.name)
  .sort();

const parts = [
  "-- GENERATED by scripts/build-seed.ts from tenants/*. Do not edit by hand.",
  "-- Fictional demo data only. Idempotent: safe to run repeatedly.",
];

for (const slug of slugs) {
  const raw = JSON.parse(readFileSync(join(tenantsDir, slug, "tenant.json"), "utf8"));
  const parsed = TenantConfigSchema.safeParse(raw);
  if (!parsed.success) {
    console.error(`tenants/${slug}/tenant.json is invalid:\n${z.prettifyError(parsed.error)}`);
    process.exit(1);
  }
  if (parsed.data.slug !== slug) {
    console.error(`tenants/${slug}: slug "${parsed.data.slug}" must match the folder name`);
    process.exit(1);
  }
  const kbDir = join(tenantsDir, slug, "kb");
  const kbDocs: KbDoc[] = existsSync(kbDir)
    ? readdirSync(kbDir)
        .filter((f) => f.endsWith(".md"))
        .sort()
        .map((f) => ({
          slug: f.replace(/\.md$/, ""),
          markdown: readFileSync(join(kbDir, f), "utf8"),
        }))
    : [];
  parts.push(buildTenantSeedSql(parsed.data, kbDocs));
  console.log(
    `✓ ${slug}: ${parsed.data.customers.length} customers, ${parsed.data.orders.length} orders, ${kbDocs.length} KB docs`,
  );
}

writeFileSync(join(root, "supabase", "seed.sql"), parts.join("\n\n") + "\n");
writeFileSync(
  join(tenantsDir, "tenant.schema.json"),
  JSON.stringify(
    z.toJSONSchema(TenantConfigSchema, { io: "input", unrepresentable: "any" }),
    null,
    2,
  ) + "\n",
);
console.log("✓ wrote supabase/seed.sql and tenants/tenant.schema.json");
