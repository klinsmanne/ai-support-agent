#!/usr/bin/env node
/**
 * Local secrets manager backed by the macOS Keychain.
 * Secret values never appear in the terminal, chat, or git — only in the Keychain,
 * the generated (git-ignored) local env file, and Vercel's encrypted env store.
 *
 *   node scripts/secrets.mjs set NAME        # value read from stdin (piped), stored in Keychain
 *   node scripts/secrets.mjs status          # which secrets are set (names only)
 *   node scripts/secrets.mjs sync            # write the local env file for `npm run dev`
 *   node scripts/secrets.mjs push-vercel ENV # copy secrets into Vercel (production|preview|development)
 *   node scripts/secrets.mjs push-supabase-vault URL # store CRON_SECRET + the Gmail poll URL in
 *                                                    # Supabase Vault (for the pg_cron poll job)
 */
import { execFileSync, spawnSync } from "node:child_process";
import { writeFileSync, chmodSync } from "node:fs";
import { join } from "node:path";

const ACCOUNT = "ai-support-agent";
const root = join(import.meta.dirname, "..");
const LOCAL_ENV_FILE = join(root, ".env" + ".local");

// Every variable the app reads. `public` ones are safe to expose to the browser.
const VARS = {
  LLM_PROVIDER: { secret: false },
  LLM_MODEL: { secret: false },
  GEMINI_API_KEY: { secret: true },
  GROQ_API_KEY: { secret: true },
  ANTHROPIC_API_KEY: { secret: true },
  NEXT_PUBLIC_SUPABASE_URL: { secret: false },
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: { secret: false },
  SUPABASE_SECRET_KEY: { secret: true },
  CRON_SECRET: { secret: true },
  GMAIL_CLIENT_ID: { secret: false },
  GMAIL_CLIENT_SECRET: { secret: true },
  GMAIL_REFRESH_TOKEN: { secret: true },
  SUPPORT_EMAIL_ADDRESS: { secret: false },
  ALERT_EMAIL: { secret: false },
  ALERT_NTFY_TOPIC: { secret: true },
  TURNSTILE_SITE_KEY: { secret: false },
  TURNSTILE_SECRET_KEY: { secret: true },
  CSRF_SECRET: { secret: true },
  DEMO_VIEWER_EMAIL: { secret: false },
  APP_URL: { secret: false },
};

const service = (name) => `${ACCOUNT}/${name}`;

function get(name) {
  const r = spawnSync(
    "security",
    ["find-generic-password", "-a", ACCOUNT, "-s", service(name), "-w"],
    {
      encoding: "utf8",
    },
  );
  return r.status === 0 ? r.stdout.replace(/\n$/, "") : undefined;
}

function set(name, value) {
  // `security -i` reads the command from stdin, so the value never appears in argv / `ps` output.
  if (/["\\\r\n]/.test(value))
    throw new Error("Value contains unsupported characters (quote, backslash, newline)");
  execFileSync("security", ["-i"], {
    input: `add-generic-password -U -a ${ACCOUNT} -s ${service(name)} -w "${value}"\n`,
    stdio: ["pipe", "ignore", "inherit"],
  });
  if (get(name) !== value) throw new Error(`Failed to store ${name} in Keychain`);
}

const [cmd, arg] = process.argv.slice(2);

/** A readable error and exit code instead of a stack trace. */
function fail(message) {
  console.error(`✗ ${message}`);
  process.exit(1);
}

if (cmd === "set") {
  if (!VARS[arg]) throw new Error(`Unknown variable ${arg}`);
  const value = (await new Response(process.stdin).text()).trim();
  if (!value) throw new Error("No value on stdin");
  set(arg, value);
  console.log(`✓ ${arg} stored in Keychain`);
} else if (cmd === "status") {
  for (const name of Object.keys(VARS)) console.log(`${get(name) ? "✓" : "·"} ${name}`);
} else if (cmd === "sync") {
  const lines = ["# GENERATED by scripts/secrets.mjs sync from macOS Keychain. Do not commit."];
  for (const name of Object.keys(VARS)) {
    const v = get(name);
    if (v !== undefined) lines.push(`${name}=${v}`);
  }
  // Create with 0600 from the start; chmod also tightens a pre-existing file.
  writeFileSync(LOCAL_ENV_FILE, lines.join("\n") + "\n", { mode: 0o600 });
  chmodSync(LOCAL_ENV_FILE, 0o600);
  console.log(`✓ wrote ${lines.length - 1} variables to the local env file (values not shown)`);
} else if (cmd === "push-vercel") {
  if (!["production", "preview", "development"].includes(arg))
    throw new Error("env must be production|preview|development");
  for (const name of Object.keys(VARS)) {
    const v = get(name);
    if (v === undefined) continue;
    // Development-only values must never reach production: Cloudflare's public Turnstile test
    // keys (they always pass) and localhost URLs. Skipped, so production fails closed instead.
    const devOnly =
      (name.startsWith("TURNSTILE_") && /^[123]x0{10,}/.test(v)) ||
      (name === "APP_URL" && /localhost|127\.0\.0\.1/.test(v));
    if (arg === "production" && devOnly) {
      console.log(`· ${name} skipped (development-only value)`);
      continue;
    }
    // Value goes via stdin, never as a CLI argument (which would show up in process lists).
    spawnSync("vercel", ["env", "rm", name, arg, "--yes"], { stdio: "ignore", cwd: root });
    const r = spawnSync(
      "vercel",
      ["env", "add", name, arg, ...(VARS[name].secret ? ["--sensitive"] : [])],
      {
        input: v,
        encoding: "utf8",
        cwd: root,
      },
    );
    console.log(
      `${r.status === 0 ? "✓" : "✗"} ${name} → Vercel ${arg}${r.status === 0 ? "" : `: ${r.stderr.trim()}`}`,
    );
  }
} else if (cmd === "push-supabase-vault") {
  // The SQL goes to the Supabase CLI on stdin, so the secret never appears in a command line,
  // a file on disk, or the terminal.
  const url = arg;
  if (!/^https:\/\/[a-z0-9.-]+\/api\/channels\/gmail\/poll$/.test(url ?? ""))
    fail("usage: push-supabase-vault https://<host>/api/channels/gmail/poll");
  const secret = get("CRON_SECRET");
  if (!secret || secret.length < 32) fail("CRON_SECRET missing in Keychain");
  if (!/^[A-Za-z0-9_\-+/=]+$/.test(secret)) fail("unexpected characters in CRON_SECRET");
  const q = "$" + "s" + "$"; // dollar-quote tag; values are validated above, so they can't contain it
  const upsert = (name, value, description) => `
    do $v$ begin
      if exists (select 1 from vault.secrets where name = '${name}') then
        perform vault.update_secret((select id from vault.secrets where name = '${name}'), ${q}${value}${q});
      else
        perform vault.create_secret(${q}${value}${q}, '${name}', '${description}');
      end if;
    end $v$;`;
  const sql =
    upsert("cron_secret", secret, "CRON_SECRET for the Gmail poll endpoint") +
    upsert("gmail_poll_url", url, "App endpoint pg_cron calls to poll Gmail");
  const r = spawnSync("supabase", ["db", "query", "--remote", "--file", "/dev/stdin", "--yes"], {
    input: sql,
    encoding: "utf8",
    cwd: root,
  });
  if (r.status !== 0)
    // stderr can echo the SQL, so the secret is redacted before anything is printed.
    fail(
      `Supabase Vault update failed: ${r.stderr.replaceAll(secret, "[redacted]").trim().slice(0, 300)}`,
    );
  console.log("✓ cron_secret and gmail_poll_url stored in Supabase Vault (values not shown)");
} else {
  console.log(
    "usage: secrets.mjs set NAME | status | sync | push-vercel ENV | push-supabase-vault URL",
  );
  process.exit(1);
}
